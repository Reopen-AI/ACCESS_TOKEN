import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Bundle the small public files into the Worker, avoiding the separate
// Workers Assets upload endpoint. Keep public/ as the editable source.
const root = new URL('./', import.meta.url);
const files = [
  ['index.html', 'text/html; charset=utf-8'],
  ['app.js', 'text/javascript; charset=utf-8'],
  ['styles.css', 'text/css; charset=utf-8'],
  ['icon.svg', 'image/svg+xml'],
];
const entries = await Promise.all(files.map(async ([name, type]) => [
  `/${name}`, { body: await readFile(new URL(`public/${name}`, root), 'utf8'), type },
]));
const source = `// Generated by build-worker.mjs. Do not edit.\n
import portal from '../src/worker.mjs';
const files = new Map(${JSON.stringify(entries)});
const assets = {
  async fetch(request) {
    const path = new URL(request.url).pathname;
    const file = files.get(path === '/' ? '/index.html' : path);
    if (!file) return new Response('Not found', { status: 404 });
    return new Response(request.method === 'HEAD' ? null : file.body, {
      headers: { 'Content-Type': file.type },
    });
  },
};
export default {
  fetch(request, env, ctx) {
    return portal.fetch(request, { ...env, ASSETS: assets }, ctx);
  },
};
`;
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/worker.mjs', root), source);
console.log(`Embedded ${entries.length} public files in the Worker.`);
